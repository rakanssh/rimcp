using System.Text;
using System.Text.RegularExpressions;

internal static class TextKeys
{
    public static string MemberName(string key)
    {
        if (!Regex.IsMatch(key, @"^RiMCP\.[A-Za-z_][A-Za-z0-9_.]*\z"))
            throw new InvalidDataException($"Cannot generate a C# resource key for '{key}'.");
        return key["RiMCP.".Length..].Replace('.', '_');
    }

    public static string Source(IEnumerable<KeyValuePair<string, string>> keys)
    {
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated>");
        code.AppendLine("// To regenerate, run this command from the repository root");
        code.AppendLine("// dotnet run --project scripts/LocalizationCatalog -- RiMCP/Languages/English/Keyed RiMCP/Source/UI/TextKeys.g.cs");
        code.AppendLine("// </auto-generated>");
        code.AppendLine();
        code.AppendLine("namespace RiMCP.UI").AppendLine("{").AppendLine("    internal static class Keys").AppendLine("    {");
        foreach (var (member, key) in keys)
            code.AppendLine($"        public static readonly TextKey @{member} = new TextKey(\"{key}\");");
        code.AppendLine("    }").AppendLine("}");
        return code.ToString();
    }
}
